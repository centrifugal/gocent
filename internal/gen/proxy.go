package main

import (
	"fmt"
	"go/format"
)

// generateProxy writes the types of the proxy package from proxy.proto: every
// message a method reachable over HTTP uses. Messages only streaming methods
// use - which only GRPC can call - and messages nothing uses are left out.
func generateProxy(s *schema) ([]byte, error) {
	used := proxyMessages(s)
	responses := map[string]bool{}
	for _, rpc := range s.methods {
		if !rpc.streaming {
			responses[rpc.response] = true
		}
	}

	w := writer{goNames: map[string]string{}}
	for _, m := range s.messages {
		for _, f := range m.fields {
			w.goNames[f.name] = goName(f.name)
		}
	}
	w.p("// Code generated by internal/gen from proxy.proto. DO NOT EDIT.")
	w.p("")
	w.p("package proxy")
	w.p("")
	w.p("import \"encoding/json/jsontext\"")

	for _, m := range s.messages {
		if !used[m.name] {
			continue
		}
		w.p("")
		if len(m.doc) > 0 {
			w.doc("", m.doc, m.name, m.name)
		} else {
			w.p("// %s is the %s message of the Centrifugo proxy protocol.", m.name, m.name)
		}
		w.p("type %s struct {", m.name)
		for i, f := range m.fields {
			if i > 0 && len(f.doc) > 0 {
				w.p("")
			}
			if len(f.doc) > 0 {
				w.doc("\t", f.doc, f.name, goName(f.name))
			}
			typ := proxyFieldType(s, f)
			// A response holds one of its fields: a pointer, so that an empty
			// result still says the request is accepted.
			if responses[m.name] && s.byName[f.typ] != nil && !f.repeated && f.mapKey == "" {
				typ = "*" + typ
			}
			w.p("\t%s %s `json:\"%s,omitzero\"`", goName(f.name), typ, f.name)
		}
		w.p("}")
	}

	src, err := format.Source(w.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated code: %w\n%s", err, w.Bytes())
	}
	return src, nil
}

// proxyFieldType is the Go type of a field: as in the API, but every message
// is a type of the proxy package, none written by hand.
func proxyFieldType(s *schema, f *field) string {
	base := f.typ
	switch {
	case scalarTypes[f.typ] != "":
		base = scalarTypes[f.typ]
	case isWrapper(s.byName[f.typ]):
		base = "*" + f.typ
	}
	switch {
	case f.mapKey != "":
		return "map[string]" + base
	case f.repeated:
		return "[]" + base
	}
	return base
}

// proxyMessages returns the messages the methods which are not streaming use,
// directly or through their fields.
func proxyMessages(s *schema) map[string]bool {
	used := map[string]bool{}
	var visit func(name string)
	visit = func(name string) {
		m := s.byName[name]
		if m == nil || used[name] {
			return
		}
		used[name] = true
		for _, f := range m.fields {
			visit(f.typ)
		}
	}
	for _, rpc := range s.methods {
		if !rpc.streaming {
			visit(rpc.request)
			visit(rpc.response)
		}
	}
	return used
}
